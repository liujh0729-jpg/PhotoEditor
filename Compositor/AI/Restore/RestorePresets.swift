/// One retouch preset in the AI Retouch & Enhance panel: what the list shows, what gets sent as the prompt,
/// and which capability slot answers. The title is a catalog key — seven languages, one row.
nonisolated struct RestorePreset: Identifiable, Sendable {
    let id: String
    /// The title as it reads in English; the catalogs carry the translation under this exact key.
    let title: String
    /// The instruction the gateway model gets. English always: it's a prompt, not UI text.
    let prompt: String
    /// Which capability slot runs it. Most retouches are edits of the given picture; the upscale family
    /// answers better from the generation slot.
    let endpointSlot: EndpointType
    let symbol: String
    /// The background generation: Vision cuts the subject on this Mac, the generation slot paints what's
    /// behind it, and the panel lays the subject back over the answer.
    var subjectCompositing = false
}

